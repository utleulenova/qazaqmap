function getRandomFact(regionId) {

    const facts = literaryFacts[regionId];

    if (!facts || facts.length === 0) {
        return "Бұл өңірдің әдеби мұрасы көптеген қаламгерлердің шығармашылығымен байланысты.";
    }

    return facts[Math.floor(Math.random() * facts.length)];
}
function addFactCard(regionId) {

    const regionCard = document.querySelector("#info .region-card");
    if (!regionCard) return;

    // Бұрынғы факт карточкасы болса өшіреміз
    const oldFact = regionCard.querySelector(".fact-card");
    if (oldFact) oldFact.remove();

    const factCard = document.createElement("div");
    factCard.className = "fact-card";

    factCard.innerHTML = `
        <div class="fact-icon">✦</div>

       <p id="literary-fact">
    ${getRandomFact(regionId)}
</p>

            <button
                class="next-fact-btn"
                onclick="changeLiteraryFact('${regionId}')">
                Басқа факт →
            </button>
        </div>
    `;

    regionCard.appendChild(factCard);
}


function changeLiteraryFact(regionId) {

    const factText = document.getElementById("literary-fact");

    if (!factText) return;

    factText.style.opacity = "0";

    setTimeout(() => {
        factText.textContent = getRandomFact(regionId);
        factText.style.opacity = "1";
    }, 180);
}
