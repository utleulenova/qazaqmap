function getFavorites() {
    return JSON.parse(localStorage.getItem("qazaqmapFavorites")) || [];
}

function toggleFavorite(regionId, writerId) {

    let favorites = getFavorites();

    const key = regionId + ":" + writerId;

    if (favorites.includes(key)) {
        favorites = favorites.filter(item => item !== key);
    } else {
        favorites.push(key);
    }

    localStorage.setItem(
        "qazaqmapFavorites",
        JSON.stringify(favorites)
    );

    updateFavoriteButton(regionId, writerId);
}

function updateFavoriteButton(regionId, writerId) {

    const button = document.getElementById("favorite-btn");

    if (!button) return;

    const key = regionId + ":" + writerId;
    const favorites = getFavorites();

    if (favorites.includes(key)) {
        button.innerHTML = "♥ Таңдаулыда";
        button.classList.add("saved");
    } else {
        button.innerHTML = "♡ Таңдаулыға қосу";
        button.classList.remove("saved");
    }
}
