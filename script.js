mapObject.addEventListener("load", () => {

    const svg = mapObject.contentDocument;

    svg.addEventListener("click", (event) => {

    const region = event.target.closest("path");

    if (!region) return;

    const id = region.id;

    if (regionNames[id]) {

        // Барлық облыстан бұрынғы highlight-ты алып тастау
        Object.keys(regionNames).forEach(regionId => {

            const path = svg.getElementById(regionId);

            if (path) {
                path.style.filter = "";
                path.style.stroke = "";
                path.style.strokeWidth = "";
            }

        });


        // Таңдалған облысты ерекшелеу
        region.style.stroke = "#fff8e9";
        region.style.strokeWidth = "4px";

        region.style.filter =
            "brightness(0.82) drop-shadow(0 3px 6px rgba(74, 49, 31, 0.45))";


        // Облыс ақпаратын ашу
        showRegion(id);
    }

});
});


