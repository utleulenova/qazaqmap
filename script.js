function showWriter(regionId, writerId) {

    const region = literatureData[regionId];

    const writer = region.writers.find(
        item => item.id === writerId
    );

    if (!writer) return;

    let worksHTML = "";

    Object.entries(writer.works).forEach(([category, works]) => {

        const items = works
            .map(work => `<li>${work}</li>`)
            .join("");

        worksHTML += `
            <div class="works-group">
                <h3>${category}</h3>

                <ul>
                    ${items}
                </ul>
            </div>
        `;
    });

    const photo = writer.image
        ? `<img src="${writer.image}" class="author-photo" alt="${writer.name}">`
        : `<div class="author-photo author-placeholder">✒️</div>`;

    info.innerHTML = `
        <div class="region-card author-page">

            <button
                class="back-btn"
                onclick="showRegion('${regionId}')">
                ← ${region.title}
            </button>

            <div class="author-header">

                ${photo}

                <div class="author-info">
                    <span class="author-small">ҚАЗАҚ ӘДЕБИЕТІ</span>
                    <h1>${writer.name}</h1>
                    <p class="author-years">${writer.years}</p>
                    <p class="author-role">${writer.role}</p>
                    <button
    class="favorite-btn"
    id="favorite-btn"
    onclick="toggleFavorite('${regionId}', '${writer.id}')">
    ♡ Таңдаулыға қосу
</button>

<button
    class="share-btn"
    onclick="shareWriter('${writer.name}')">
    ↗ Бөлісу
</button>
                </div>

            </div>

            <div class="author-section">

                <div class="author-block">
                    <span class="mini-title">ӨМІРБАЯНЫ</span>
                    <h2>Жазушы туралы</h2>
                    <p>${writer.bio}</p>
                </div>

                <div class="author-block">

                    <div class="works-grid">
                        ${worksHTML}
                    </div>
                </div>

            </div>
        </div>
    `;

    scrollToInfo();
}


