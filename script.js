const liveSearchInput = document.getElementById("writer-search");
const searchResults = document.getElementById("search-results");

if (liveSearchInput && searchResults) {

    liveSearchInput.addEventListener("input", function () {

        const query = this.value.trim().toLowerCase();

        searchResults.innerHTML = "";

        if (query.length < 2) {
            searchResults.classList.remove("show");
            return;
        }

        const matches = [];

        Object.entries(literatureData).forEach(([regionId, region]) => {

            region.writers.forEach(writer => {

                if (writer.name.toLowerCase().includes(query)) {

                    matches.push({
                        writer,
                        regionId,
                        regionName: region.name || regionNames[regionId]
                    });

                }
            });

        });

        if (matches.length === 0) {

            searchResults.innerHTML = `
                <div class="search-empty">
                    Жазушы табылмады
                </div>
            `;

            searchResults.classList.add("show");
            return;
        }

        matches.slice(0, 6).forEach(item => {

            const result = document.createElement("button");

            result.className = "search-result-item";

            result.innerHTML = `
                <strong>${item.writer.name}</strong>
                <span>${item.regionName}</span>
            `;

            result.addEventListener("click", function () {

                showWriter(item.regionId, item.writer.id);

                liveSearchInput.value = "";
                searchResults.innerHTML = "";
                searchResults.classList.remove("show");

            });

            searchResults.appendChild(result);

        });

        searchResults.classList.add("show");

    });

}
